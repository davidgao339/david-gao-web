function getMetricDescription(key, val, lang) {
  lang = lang || getLang();
  const blurbs = METRIC_BLURBS_I18N[lang] || METRIC_BLURBS_I18N.en;
  if (!blurbs[key]) return '';
  
  if (key === 'heart' || key === 'emotional') {
    return val >= 60 ? blurbs[key].high : blurbs[key].low;
  }
  if (key === 'physical') {
    if (val >= 60) return blurbs.physical.high;
    if (val > 0) return blurbs.physical.med;
    return blurbs.physical.low;
  }
  return '';
}

