function getLang() {
  return I18N_STATE.currentLang || 'en';
}

function setLang(lang) {
  if (lang === 'ru' || lang === 'en') {
    I18N_STATE.currentLang = lang;
    localStorage.setItem('waves_lang', lang);
  }
}

