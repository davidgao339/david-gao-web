function calcZodiacRoles(mDay, mMonth, fDay, fMonth) {
  const mIdx = zodiacIndex(mDay, mMonth);
  const fIdx = zodiacIndex(fDay, fMonth);
  const mPos = mIdx + 1, fPos = fIdx + 1;

  const rawDiff = Math.abs(mPos - fPos);
  const distance = Math.min(rawDiff, 12 - rawDiff);
  const info = ROLE_INFO[distance];

  let zodiacRoleMale, zodiacRoleFemale, zodiacRoleDifference;
  if (distance === 0) {
    zodiacRoleMale = zodiacRoleFemale = info.name;
    zodiacRoleDifference = 'Одинаковые знаки';
  } else {
    // whoever the OTHER person is "ahead of" (circularly, by `distance`
    // steps) takes the senior/first-listed role.
    const femaleAheadOfMale = (fPos - mPos + 12) % 12 === distance;
    zodiacRoleMale = femaleAheadOfMale ? info.names[0] : info.names[1];
    zodiacRoleFemale = femaleAheadOfMale ? info.names[1] : info.names[0];
    zodiacRoleDifference = `+${distance} и -${distance} позиций`;
  }

  return {
    zodiacRoleTitle: info.title,
    zodiacRoleDifference,
    zodiacRoleMale,
    zodiacRoleFemale,
    zodiacRoleDescription: info.description,
    zodiacPairText: `Союз ${ZODIAC_SIGNS[mIdx].name} и ${ZODIAC_SIGNS[fIdx].name} — это сочетание «${info.title.replace(/«|»/g, '')}». ${info.description}`,
    positions: [mPos, fPos, rawDiff],
  };
}

