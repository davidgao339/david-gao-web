/* ============================================================
   CHAKRA BIORHYTHM COMPATIBILITY
   ============================================================ */

const CHAKRA_PERIODS = {
  physical: 23.69, emotional: 28.43, intellect: 33.16, heart: 37.90,
  creative: 42.64, intuitive: 47.38, highest: 52.11,
};

function calcChakra(mDateMs, fDateMs) {
  const datesDiff = Math.round(Math.abs(fDateMs - mDateMs) / 86400000);

  const chart = {};
  const labels = {};
  let compatCount = 0, dissonanceCount = 0;
  const compatibleKeys = [];

  for (const [key, T] of Object.entries(CHAKRA_PERIODS)) {
    const raw = ((Math.cos(2 * Math.PI * datesDiff / T) + 1) / 2) * 100;
    const val = Math.round(raw);
    chart[key] = val;
    labels[`${key}-label`] = val >= 75 ? 'Высокая' : (val <= 15 ? 'Низкая' : '');
    if (val >= 55) { compatCount++; compatibleKeys.push(key); }
    if (val < 20) dissonanceCount++;
  }

  const CLASS_MAP = {
    physical: 'circle-phyz', emotional: 'circle-emo', intellect: 'circle-intel',
    heart: 'circle-heart', creative: 'circle-creat', intuitive: 'circle-intuit', highest: 'circle-high',
  };

  const balanceMale = Object.values(chart).reduce((a, v) => a + v, 0) + digitSum(mDateMs / 86400000) * 10;
  const balanceFemale = Object.values(chart).reduce((a, v) => a + v, 0) + digitSum(fDateMs / 86400000) * 10;
  let balanceTotal;
  if (Math.abs(balanceMale - balanceFemale) <= 15) balanceTotal = 'Баланс ровный';
  else if (balanceFemale > balanceMale) balanceTotal = 'Баланс «женский» — благоприятно';
  else balanceTotal = 'Баланс «мужской» — благоприятно';

  return {
    bio_result_top: {
      datesDiff,
      totalCompatibility: `${compatCount} совместимост${compatCount === 1 ? 'ь' : (compatCount >= 2 && compatCount <= 4 ? 'и' : 'ей')}`,
      totalDissonance: dissonanceCount === 0 ? 'Нет диссонансов' : `${dissonanceCount} диссонанс${dissonanceCount === 1 ? '' : (dissonanceCount <= 4 ? 'а' : 'ов')}`,
      chakreClasses: compatibleKeys.map(k => CLASS_MAP[k]),
    },
    bio_result_chart: chart,
    bio_result_chart_labels: labels,
    bio_result_balance: { balanceTotal, balanceFemale: Math.round(balanceFemale), balanceMale: Math.round(balanceMale) },
  };
}

/* ============================================================
   FATE & WILL CHART
   Only fate[0]/fate[1]/fate[6] are actually solved — cross-validated
   against 3 independent real data points spanning different years
   (day15/1990, day20/1985, day15/2000 all matched this day-only formula
   for those three indices). fate[2..5] and the entire will[] array were
   NOT solved: an early hypothesis assumed they were constant, but that
   turned out to be an artifact of testing only within year 2000 — real
   data shows they vary by year/month in a way we didn't crack. day<5 is
   an even less-tested edge case (the live API returns a 6-key object
   with a missing index there — see CLAUDE.md). Treat this chart as
   decorative/approximate, not a validated reproduction.
   ============================================================ */

function calcFaw(day, month, year) {
  const base = day >= 5 ? 1 + Math.floor((day - 5) / 5) : 2 * day;
  const mid1 = day >= 5 ? 2 * ((day - 5) % 5) : 2;

  // fate[2..5]: unsolved — vary plausibly with month/year so the chart
  // isn't flatly wrong, but this is a guess, not a derived formula.
  const salt = digitSum(month * 7 + digitSum(year));
  const fate = [base, mid1, digitSum(salt + 2), digitSum(salt + 3), digitSum(salt + 4), digitSum(salt), base];

  // will[]: never solved at all — approximate with a related but
  // distinct curve so the chart looks organic rather than duplicating fate[].
  const will = fate.map((v, i) => digitSum(v * 2 + salt + i));

  return { fate, will };
}

